#!/usr/bin/env node
// Generates a Supabase SQL migration for Maldives Fishing and Holiday Pvt
// Ltd (MFH) — the real fishing charter/package operator described in the
// owner-supplied rate sheets (MFH_Charter_Rate_sheet_.pdf,
// MFH_Packages_Rate_sheet_.pdf, both valid until 31 December 2027).
//
// Source of truth: data/maldives/fishing/mfh-charters.json (2 entries) and
// data/maldives/fishing/mfh-packages.json (14 entries — 7 durations x 2
// fishing-day types), plus data/maldives/fishing/SOURCES-mfh.md for the
// full pricing-provenance writeup.
//
// Website selling price = source PDF price - USD 20, applied per the
// owner's explicit instruction, computed once in
// /tmp/.../scratchpad/mfh-pricing.py and carried into the two source JSON
// files above (price_from = website price, price_from_source = the
// original PDF figure) — never recomputed here, so this script cannot
// silently drift from the documented calculation.
//
// Reuses the existing schema exactly like every other Task 4-11 generator:
// nodes/providers/accommodations/activities/packages/package_itinerary_*/
// node_locations/node_categories/bookable_products. No new tables, no new
// columns. The one new real entity this introduces beyond what
// generate-fishing-seed.mjs already covers is the accommodation itself
// (Maldives Fishing and Holidays Lodge, a guesthouse on Maamendhoo, Gaafu
// Alifu Atoll — genuinely described across both PDFs, not invented) and
// its operating provider.
//
// The full 1-5 guest pricing table from the packages PDF does not fit the
// existing single `packages.price_from` column (one number), so
// `price_from` here is set to the lowest verified per-person rate (the
// 5-guest "best value" tier, exactly as the PDF itself labels it) and the
// complete table is exposed to the frontend separately via
// src/lib/packages/mfh-price-tables.ts (generated by this same script from
// the same JSON, so the two can never drift apart) rather than as a new
// migration/table.
//
// Idempotent (ON CONFLICT ... DO NOTHING / natural unique constraints),
// same convention as every other generator in this directory.
//
// Usage: node scripts/generate-mfh-seed.mjs

import { createHash } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

import { DATA_DIR, ROOT } from "./lib/legacy-shared.mjs";

const FISHING_DATA_DIR = path.join(DATA_DIR, "fishing");
const MIGRATION_PATH = path.join(ROOT, "supabase", "migrations", "20250119000100_seed_mfh_fishing.sql");
const PRICE_TABLE_PATH = path.join(ROOT, "src", "lib", "packages", "mfh-price-tables.ts");

// Maamendhoo, Gaafu Alifu Atoll already exists — confirmed against
// supabase/migrations/20250102000100_seed_maldives_locations.sql (line
// 2138) rather than re-derived, since Maamendhoo also independently exists
// as a DIFFERENT island in Laamu Atoll and this script must resolve the
// correct one.
const MAAMENDHOO_GA_SLUG = "maamendhoo-gaafu-alifu";

const PROVIDER_SLUG = "maldives-fishing-and-holiday";
const PROVIDER_NAME = "Maldives Fishing and Holiday Pvt Ltd";
const ACCOMMODATION_SLUG = "maldives-fishing-and-holidays-lodge";
const ACCOMMODATION_NAME = "Maldives Fishing and Holidays Lodge";

// Matches generate-package-seed.mjs's durationBandSlug() exactly — the
// real seeded duration-band taxonomy (20250101001500_seed_taxonomy.sql)
// only has {3,4,5,7,10,14}-nights + 'custom', not an arbitrary range set.
const DURATION_BANDS = new Set([3, 4, 5, 7, 10, 14]);
function durationBandSlug(nights) {
  return DURATION_BANDS.has(nights) ? `${nights}-nights` : "custom";
}

function slugify(input) {
  return input
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "")
    .replace(/['’]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

function sqlString(value) {
  if (value === null || value === undefined) return "null";
  return `'${String(value).replace(/'/g, "''")}'`;
}

function sqlLiteral(value) {
  if (value === null || value === undefined) return "null";
  if (typeof value === "boolean") return value ? "true" : "false";
  return String(value);
}

function deterministicUuid(key) {
  const hex = createHash("sha1").update(key).digest("hex").slice(0, 32);
  return `${hex.slice(0, 8)}-${hex.slice(8, 12)}-${hex.slice(12, 16)}-${hex.slice(16, 20)}-${hex.slice(20, 32)}`;
}

function loadJson(file) {
  const full = path.join(FISHING_DATA_DIR, file);
  if (!existsSync(full)) throw new Error(`Missing required data file: ${full}`);
  return JSON.parse(readFileSync(full, "utf8"));
}

function main() {
  const charters = loadJson("mfh-charters.json");
  const packages = loadJson("mfh-packages.json");

  const lines = [];
  lines.push("-- Maldives Fishing and Holiday Pvt Ltd (MFH) — real fishing charter and");
  lines.push("-- package operator, sourced from the owner-supplied rate sheets (valid");
  lines.push("-- until 31 December 2027). GENERATED FILE — do not hand-edit.");
  lines.push("-- Source of truth:");
  lines.push("--   data/maldives/fishing/mfh-charters.json");
  lines.push("--   data/maldives/fishing/mfh-packages.json");
  lines.push("--   data/maldives/fishing/SOURCES-mfh.md");
  lines.push("-- Regenerate with: node scripts/generate-mfh-seed.mjs");
  lines.push("--");
  lines.push("-- Website prices = source PDF price - USD 20 (owner's explicit pricing");
  lines.push("-- rule), computed once outside this script and carried in the JSON above");
  lines.push("-- as price_from (website) / price_from_source (PDF) — never recomputed");
  lines.push("-- here. No new tables/columns — reuses nodes/providers/accommodations/");
  lines.push("-- activities/packages/package_itinerary_* exactly as seeded by Tasks 5-11.");
  lines.push("");

  // ── Provider ──
  lines.push("-- Provider");
  lines.push(`insert into nodes (node_type, slug, title, summary, status, published_at)`);
  lines.push(
    `values ('provider', ${sqlString(PROVIDER_SLUG)}, ${sqlString(PROVIDER_NAME)}, ${sqlString(`${PROVIDER_NAME} operates fishing charters and fishing holiday packages from Maamendhoo, Gaafu Alifu Atoll, Maldives.`)}, 'published', now())`,
  );
  lines.push(`on conflict (node_type, slug) do nothing;`);
  lines.push("");
  lines.push(`insert into providers (id, website_url, contact_email, contact_phone, legal_name, license_number, is_verified)`);
  lines.push(
    `select id, 'https://www.maldivesfishing.com/', 'safooh@maldivesfishing.com', '+960 7444509', 'Maldives Fishing and Holiday Pvt Ltd', 'C40602025', true`,
  );
  lines.push(`from nodes where node_type = 'provider' and slug = ${sqlString(PROVIDER_SLUG)}`);
  lines.push(`on conflict (id) do nothing;`);
  lines.push("");

  // ── Accommodation ──
  lines.push("-- Accommodation (guesthouse)");
  lines.push(`insert into nodes (node_type, slug, title, summary, status, meta_title, meta_description, published_at)`);
  lines.push(
    `values ('accommodation', ${sqlString(ACCOMMODATION_SLUG)}, ${sqlString(ACCOMMODATION_NAME)}, ${sqlString("Maldives Fishing and Holidays Lodge is a guesthouse on Maamendhoo, Gaafu Alifu Atoll, run by Maldives Fishing and Holiday Pvt Ltd, offering full-board rooms for up to 2 guests alongside the operator's own private fishing charters.")}, 'published', ${sqlString(`${ACCOMMODATION_NAME} | Maldives Guesthouses | MTG`)}, ${sqlString("Maldives Fishing and Holidays Lodge is a guesthouse on Maamendhoo, Gaafu Alifu Atoll, offering full-board rooms alongside private fishing charters.")}, now())`,
  );
  lines.push(`on conflict (node_type, slug) do nothing;`);
  lines.push("");
  lines.push(`insert into accommodations (id, accommodation_type, operated_by_provider_id, star_rating, room_count, all_inclusive, overwater_villas)`);
  lines.push(
    `select n.id, 'guesthouse', p.id, null, null, true, false from nodes n, nodes p where n.node_type = 'accommodation' and n.slug = ${sqlString(ACCOMMODATION_SLUG)} and p.node_type = 'provider' and p.slug = ${sqlString(PROVIDER_SLUG)}`,
  );
  lines.push(`on conflict (id) do nothing;`);
  lines.push("");
  lines.push(`insert into node_locations (node_id, location_id, relation)`);
  lines.push(
    `select n.id, l.id, 'primary' from nodes n, nodes l where n.node_type = 'accommodation' and n.slug = ${sqlString(ACCOMMODATION_SLUG)} and l.node_type = 'location' and l.slug = ${sqlString(MAAMENDHOO_GA_SLUG)}`,
  );
  lines.push(`on conflict (node_id, location_id) do nothing;`);
  lines.push("");
  lines.push(`insert into bookable_products (id, booking_mode)`);
  lines.push(`select id, 'inquiry' from nodes where node_type = 'accommodation' and slug = ${sqlString(ACCOMMODATION_SLUG)}`);
  lines.push(`on conflict (id) do nothing;`);
  lines.push("");

  // ── Charter activities ──
  const activitySlugBySlug = new Map();
  for (const c of charters) {
    const slug = slugify(c.name);
    activitySlugBySlug.set(c.activity_slug ?? slug, slug);

    const summary = `${c.name} is a private ${c.day_type === "full-day" ? "full-day" : "half-day"} fishing charter aboard "${c.boat_name}", a ${c.boat_length_ft}-foot fishing boat (${c.boat_engine}), departing from Maamendhoo, Gaafu Alifu Atoll. Operated by ${c.operator_name}. From ${c.currency} ${c.price_from} ${c.price_unit} (source rate ${c.currency} ${c.source_price}).`;
    const metaTitle = `${c.name} | Maldives Fishing | MTG`;

    lines.push(`-- Charter activity: ${c.name}`);
    lines.push(`insert into nodes (node_type, slug, title, summary, status, meta_title, meta_description, published_at)`);
    lines.push(
      `values ('activity', ${sqlString(slug)}, ${sqlString(c.name)}, ${sqlString(summary)}, 'published', ${sqlString(metaTitle)}, ${sqlString(summary)}, now())`,
    );
    lines.push(`on conflict (node_type, slug) do nothing;`);
    lines.push("");

    lines.push(`insert into activities (id, activity_category, operated_by_provider_id, duration_minutes, price_from, currency, max_participants)`);
    lines.push(`select n.id, 'fishing', p.id, ${c.day_type === "full-day" ? 480 : 240}, ${sqlLiteral(c.price_from)}, ${sqlString(c.currency)}, ${sqlLiteral(c.max_participants)}`);
    lines.push(`from nodes n, nodes p where n.node_type = 'activity' and n.slug = ${sqlString(slug)} and p.node_type = 'provider' and p.slug = ${sqlString(PROVIDER_SLUG)}`);
    lines.push(`on conflict (id) do nothing;`);
    lines.push("");

    lines.push(`insert into node_locations (node_id, location_id, relation)`);
    lines.push(
      `select n.id, l.id, 'primary' from nodes n, nodes l where n.node_type = 'activity' and n.slug = ${sqlString(slug)} and l.node_type = 'location' and l.slug = ${sqlString(MAAMENDHOO_GA_SLUG)}`,
    );
    lines.push(`on conflict (node_id, location_id) do nothing;`);
    lines.push("");

    lines.push(`insert into bookable_products (id, booking_mode, base_price, currency, max_guests)`);
    lines.push(`select id, 'inquiry', ${sqlLiteral(c.price_from)}, ${sqlString(c.currency)}, ${sqlLiteral(c.max_participants)} from nodes where node_type = 'activity' and slug = ${sqlString(slug)}`);
    lines.push(`on conflict (id) do nothing;`);
    lines.push("");
  }

  // ── Packages ──
  let packageCount = 0;
  let stageCount = 0;
  let itemCount = 0;
  for (const pkg of packages) {
    const slug = slugify(pkg.name);
    const activitySlug = activitySlugBySlug.get(pkg.activity_slug);
    if (!activitySlug) throw new Error(`Package "${pkg.name}": unresolved activity_slug "${pkg.activity_slug}"`);

    const summary = `${pkg.name} is a ${pkg.nights}-night, ${pkg.fishing_days}-day fishing holiday at ${ACCOMMODATION_NAME} on Maamendhoo, Gaafu Alifu Atoll, including full-board accommodation, return domestic flight, boat transfer, and ${pkg.day_type === "full-day" ? "full-day" : "half-day"} private fishing charters. From ${pkg.currency} ${pkg.price_from} per person (${pkg.price_basis}; source rate ${pkg.currency} ${pkg.price_from_source}).`;
    const metaTitle = `${pkg.name} | Maldives Fishing Packages | MTG`;

    lines.push(`-- Package: ${pkg.name}`);
    lines.push(`insert into nodes (node_type, slug, title, summary, status, meta_title, meta_description, published_at)`);
    lines.push(
      `values ('package', ${sqlString(slug)}, ${sqlString(pkg.name)}, ${sqlString(summary)}, 'published', ${sqlString(metaTitle)}, ${sqlString(summary)}, now())`,
    );
    lines.push(`on conflict (node_type, slug) do nothing;`);
    lines.push("");

    lines.push(`insert into packages (id, duration_nights, price_from, currency, operated_by_provider_id)`);
    lines.push(
      `select n.id, ${sqlLiteral(pkg.nights)}, ${sqlLiteral(pkg.price_from)}, ${sqlString(pkg.currency)}, p.id from nodes n, nodes p where n.node_type = 'package' and n.slug = ${sqlString(slug)} and p.node_type = 'provider' and p.slug = ${sqlString(PROVIDER_SLUG)}`,
    );
    lines.push(`on conflict (id) do nothing;`);
    lines.push("");

    lines.push(`insert into bookable_products (id, booking_mode, base_price, currency)`);
    lines.push(`select id, 'inquiry', ${sqlLiteral(pkg.price_from)}, ${sqlString(pkg.currency)} from nodes where node_type = 'package' and slug = ${sqlString(slug)}`);
    lines.push(`on conflict (id) do nothing;`);
    lines.push("");
    packageCount += 1;

    // Taxonomy: fishing theme/category tag + duration band (reuses the
    // exact tags already seeded by Task 7/11 — no new categories).
    for (const tagSlug of ["fishing", durationBandSlug(pkg.nights)]) {
      lines.push(`insert into node_categories (node_id, category_id)`);
      lines.push(`select n.id, c.id from nodes n, nodes c where n.node_type = 'package' and n.slug = ${sqlString(slug)} and c.node_type = 'category' and c.slug = ${sqlString(tagSlug)}`);
      lines.push(`on conflict (node_id, category_id) do nothing;`);
      lines.push("");
    }

    lines.push(`insert into node_locations (node_id, location_id, relation)`);
    lines.push(
      `select n.id, l.id, 'primary' from nodes n, nodes l where n.node_type = 'package' and n.slug = ${sqlString(slug)} and l.node_type = 'location' and l.slug = ${sqlString(MAAMENDHOO_GA_SLUG)}`,
    );
    lines.push(`on conflict (node_id, location_id) do nothing;`);
    lines.push("");

    // Stage 1: arrival + accommodation + the fishing charter for the whole stay.
    lines.push(`insert into package_itinerary_stages (package_id, stage_number, day_start, day_end, night_count, title, description, sort_order)`);
    lines.push(
      `select id, 1, 1, ${sqlLiteral(pkg.nights)}, ${sqlLiteral(pkg.nights)}, ${sqlString(ACCOMMODATION_NAME)}, ${sqlString(`${pkg.nights} nights at ${ACCOMMODATION_NAME}, Maamendhoo, Gaafu Alifu Atoll, with ${pkg.fishing_days} day${pkg.fishing_days === 1 ? "" : "s"} of ${pkg.day_type === "full-day" ? "full-day" : "half-day"} private fishing aboard "Emperor". Full-board meals, airport meet and greet, return domestic flight, and boat transfer included.`)}, 1`,
    );
    lines.push(`from nodes where node_type = 'package' and slug = ${sqlString(slug)}`);
    lines.push(`on conflict (package_id, stage_number) do nothing;`);
    lines.push("");
    stageCount += 1;

    const accItemId = deterministicUuid(`package-item::${slug}::1::0::accommodation`);
    lines.push(`insert into package_itinerary_items (id, stage_id, component_type, component_node_id, component_role, quantity, sort_order)`);
    lines.push(`select ${sqlString(accItemId)}::uuid, s.id, 'node', comp.id, 'accommodation', 1, 0`);
    lines.push(`from package_itinerary_stages s join nodes p on p.id = s.package_id join nodes comp on comp.node_type = 'accommodation' and comp.slug = ${sqlString(ACCOMMODATION_SLUG)}`);
    lines.push(`where p.node_type = 'package' and p.slug = ${sqlString(slug)} and s.stage_number = 1`);
    lines.push(`on conflict (id) do nothing;`);
    lines.push("");
    itemCount += 1;

    const actItemId = deterministicUuid(`package-item::${slug}::1::1::activity`);
    lines.push(`insert into package_itinerary_items (id, stage_id, component_type, component_node_id, component_role, quantity, notes, sort_order)`);
    lines.push(
      `select ${sqlString(actItemId)}::uuid, s.id, 'node', comp.id, 'activity', ${sqlLiteral(pkg.fishing_days)}, ${sqlString(`${pkg.fishing_days} day${pkg.fishing_days === 1 ? "" : "s"} of fishing during the stay.`)}, 1`,
    );
    lines.push(`from package_itinerary_stages s join nodes p on p.id = s.package_id join nodes comp on comp.node_type = 'activity' and comp.slug = ${sqlString(activitySlug)}`);
    lines.push(`where p.node_type = 'package' and p.slug = ${sqlString(slug)} and s.stage_number = 1`);
    lines.push(`on conflict (id) do nothing;`);
    lines.push("");
    itemCount += 1;

    // Stage 2: departure.
    lines.push(`insert into package_itinerary_stages (package_id, stage_number, day_start, day_end, night_count, title, description, sort_order)`);
    lines.push(
      `select id, 2, ${sqlLiteral(pkg.nights + 1)}, ${sqlLiteral(pkg.nights + 1)}, 0, 'Departure', ${sqlString("Boat transfer to the domestic airport and return domestic flight to Velana International Airport, timed around the guest's international flight.")}, 2`,
    );
    lines.push(`from nodes where node_type = 'package' and slug = ${sqlString(slug)}`);
    lines.push(`on conflict (package_id, stage_number) do nothing;`);
    lines.push("");
    stageCount += 1;
  }

  writeFileSync(MIGRATION_PATH, lines.join("\n") + "\n");
  console.log(`Wrote ${path.relative(ROOT, MIGRATION_PATH)}`);
  console.log(`Charters: ${charters.length}, Packages: ${packageCount}, Stages: ${stageCount}, Items: ${itemCount}`);

  // ── Static price-table TS file (frontend-only, no schema) ──
  const tsLines = [];
  tsLines.push("// Full 1-5 guest pricing table per MFH fishing package (Task 22).");
  tsLines.push("// GENERATED FILE — do not hand-edit. Source of truth:");
  tsLines.push("//   data/maldives/fishing/mfh-packages.json");
  tsLines.push("// Regenerate with: node scripts/generate-mfh-seed.mjs");
  tsLines.push("//");
  tsLines.push("// packages.price_from (the DB column) only holds one number, so it's set");
  tsLines.push("// to the lowest verified per-person rate (the 5-guest \"best value\" tier —");
  tsLines.push("// see generate-mfh-seed.mjs's header comment). This file carries the FULL");
  tsLines.push("// 1-5 guest table from the same source JSON, so the package detail page");
  tsLines.push("// can render the real pricing table without a schema change, and can never");
  tsLines.push("// drift from price_from since both come from the same run of this script.");
  tsLines.push("");
  tsLines.push("export interface MfhGuestPrice {");
  tsLines.push("  guests: number;");
  tsLines.push("  sourcePrice: number;");
  tsLines.push("  websitePrice: number;");
  tsLines.push("  isBestValue: boolean;");
  tsLines.push("}");
  tsLines.push("");
  tsLines.push("export const MFH_PRICE_TABLES: Record<string, MfhGuestPrice[]> = {");
  for (const pkg of packages) {
    const slug = slugify(pkg.name);
    const rows = pkg.guest_pricing
      .map((g) => `    { guests: ${g.guests}, sourcePrice: ${g.sourcePrice}, websitePrice: ${g.websitePrice}, isBestValue: ${g.isBestValue} }`)
      .join(",\n");
    tsLines.push(`  ${JSON.stringify(slug)}: [\n${rows},\n  ],`);
  }
  tsLines.push("};");
  writeFileSync(PRICE_TABLE_PATH, tsLines.join("\n") + "\n");
  console.log(`Wrote ${path.relative(ROOT, PRICE_TABLE_PATH)}`);
}

main();
